#!/usr/bin/env node
// Render the spoken voice-failure phrases to 12 kHz mu-law and embed them in the app.
// The phrases must play when the host is unreachable, so they ship with the app instead
// of coming from host TTS.
//
// Usage: node scripts/generate-voice-failure-phrases.mjs [kokoro-model-dir]
// Default model dir: ~/.paseo/models/local-speech/kokoro-en-v0_19 (Kokoro, Apache-2.0)

import { createRequire } from "node:module";
import { homedir } from "node:os";
import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, resolve } from "node:path";

const here = dirname(fileURLToPath(import.meta.url));
const target = resolve(here, "../src/voice/voice-failure-phrases.mulaw.ts");
const modelDir =
  process.argv[2] ?? resolve(homedir(), ".paseo/models/local-speech/kokoro-en-v0_19");

// A different Kokoro voice from the agent's default (sid 0), so a failure never sounds
// like the agent talking. 9 is bm_george.
const SPEAKER_ID = 9;
const OUTPUT_RATE = 12000;
const PEAK = 0.45;

const PHRASES = {
  "nothing-recognized": "Didn't catch that.",
  "recognition-stalled": "Recognition stalled.",
  "recognition-failed": "Recognition failed.",
  "recognition-unavailable": "Recognition unavailable.",
  "host-disconnected": "Host disconnected.",
  "microphone-lost": "Microphone lost.",
  reconnected: "Reconnected.",
};

const require = createRequire(resolve(here, "../../server/package.json"));
const sherpa = require("sherpa-onnx-node");
const tts = new sherpa.OfflineTts({
  model: {
    numThreads: 2,
    provider: "cpu",
    kokoro: {
      model: `${modelDir}/model.onnx`,
      voices: `${modelDir}/voices.bin`,
      tokens: `${modelDir}/tokens.txt`,
      dataDir: `${modelDir}/espeak-ng-data`,
      lengthScale: 1.0,
    },
  },
  maxNumSentences: 1,
});

function trimSilence(samples) {
  const threshold = 0.01;
  let start = 0;
  let end = samples.length;
  while (start < end && Math.abs(samples[start]) < threshold) start += 1;
  while (end > start && Math.abs(samples[end - 1]) < threshold) end -= 1;
  return samples.subarray(start, end);
}

function resample(input, inputRate) {
  // Box low-pass before decimating so sibilance above the new Nyquist does not alias.
  const width = Math.max(1, Math.round(inputRate / OUTPUT_RATE));
  const samples = new Float32Array(input.length);
  for (let i = 0; i < input.length; i += 1) {
    let sum = 0;
    for (let k = 0; k < width; k += 1) sum += input[Math.min(i + k, input.length - 1)];
    samples[i] = sum / width;
  }
  const length = Math.floor((samples.length * OUTPUT_RATE) / inputRate);
  const out = new Float32Array(length);
  for (let i = 0; i < length; i += 1) {
    const position = (i * inputRate) / OUTPUT_RATE;
    const index = Math.floor(position);
    const fraction = position - index;
    const next = samples[Math.min(index + 1, samples.length - 1)];
    out[i] = samples[index] * (1 - fraction) + next * fraction;
  }
  return out;
}

// G.711 mu-law: half the size of PCM16 at telephone quality. The app expands it back.
function encodeMuLaw(sample) {
  const BIAS = 0x84;
  const CLIP = 32635;
  const sign = sample < 0 ? 0x80 : 0;
  let magnitude = Math.min(CLIP, Math.abs(sample)) + BIAS;
  let exponent = 7;
  for (let mask = 0x4000; (magnitude & mask) === 0 && exponent > 0; mask >>= 1) exponent -= 1;
  const mantissa = (magnitude >> (exponent + 3)) & 0x0f;
  return ~(sign | (exponent << 4) | mantissa) & 0xff;
}

function toMuLaw(samples) {
  let peak = 0;
  for (const sample of samples) peak = Math.max(peak, Math.abs(sample));
  const gain = peak > 0 ? PEAK / peak : 1;
  const out = Buffer.alloc(samples.length);
  for (let i = 0; i < samples.length; i += 1) {
    const value = Math.max(-1, Math.min(1, samples[i] * gain));
    out[i] = encodeMuLaw(Math.round(value * 32767));
  }
  return out;
}

const lines = [
  "// Generated by scripts/generate-voice-failure-phrases.mjs. Do not edit by hand.",
  `// Kokoro (Apache-2.0) voice ${SPEAKER_ID}, G.711 mu-law mono ${OUTPUT_RATE} Hz, base64.`,
  "",
  `export const VOICE_FAILURE_PHRASE_SAMPLE_RATE = ${OUTPUT_RATE};`,
  "",
  "export const VOICE_FAILURE_PHRASE_MULAW_BASE64 = {",
];
for (const [key, text] of Object.entries(PHRASES)) {
  const audio = await tts.generateAsync({
    text,
    sid: SPEAKER_ID,
    speed: 1.05,
    enableExternalBuffer: false,
  });
  const samples = trimSilence(Float32Array.from(audio.samples));
  const encoded = toMuLaw(resample(samples, audio.sampleRate));
  const ms = Math.round((encoded.length / OUTPUT_RATE) * 1000);
  console.log(`${key}: "${text}" ${ms} ms, ${encoded.length} bytes`);
  lines.push(`  // "${text}" (${ms} ms)`);
  lines.push(`  ${JSON.stringify(key)}:`);
  lines.push(`    "${encoded.toString("base64")}",`);
}
lines.push("} as const;", "");
writeFileSync(target, lines.join("\n"));
console.log(`Wrote ${target}`);
